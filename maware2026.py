def build_vocab(train_lists, V):
    from collections import Counter
    cnt = Counter()
    for t in train_lists: cnt.update(t)
    top = [w for w,_ in cnt.most_common(V-2)]      # reserve 0=PAD,1=UNK
    return {w:i+2 for i,w in enumerate(top)}

def to_ids(lists, vocab, L):
    out = np.zeros((len(lists), L), dtype=np.int64)
    for i,t in enumerate(lists):
        ids = [vocab.get(w,1) for w in t[:L]]
        out[i,:len(ids)] = ids
    return out

# ---------------- 3. MODELS (token-embedding front end) ----------------
class BSpline(nn.Module):
    def __init__(s,n=8,d=3):
        super().__init__(); s.d=d; s.register_buffer("k",torch.linspace(-1,1,n+d+1))
    def forward(s,x):
        x=x.unsqueeze(-1); k=s.k; b=((x>=k[:-1])&(x<k[1:])).float()
        for j in range(1,s.d+1):
            ln=x-k[:-(j+1)]; ld=(k[j:-1]-k[:-(j+1)]).clamp(min=1e-8)
            rn=k[j+1:]-x;    rd=(k[j+1:]-k[1:(-j if j>0 else None)]).clamp(min=1e-8)
            b=(ln/ld)*b[...,:-1]+(rn/rd)*b[...,1:]
        return b
class KANLayer(nn.Module):
    def __init__(s,i,o,n=8):
        super().__init__(); s.bs=BSpline(n); s.c=nn.Parameter(torch.randn(i,o,n)*0.1)
        s.lin=nn.Linear(i,o); s.nm=nn.LayerNorm(o)
    def forward(s,x):
        return s.nm(torch.einsum("bin,ion->bo",s.bs(torch.tanh(x)),s.c)+F.silu(s.lin(x)))
class SelectiveSSM(nn.Module):
    def __init__(s,dm,ds=16,dc=4,ex=2):
        super().__init__(); s.di=dm*ex; s.ds=ds
        s.inp=nn.Linear(dm,s.di*2,bias=False)
        s.cv=nn.Conv1d(s.di,s.di,dc,padding=dc-1,groups=s.di,bias=True)
        s.xp=nn.Linear(s.di,ds*2+1,bias=False); s.dtp=nn.Linear(1,s.di,bias=True)
        A=torch.arange(1,ds+1,dtype=torch.float32).unsqueeze(0).expand(s.di,-1)
        s.Al=nn.Parameter(torch.log(A.clone())); s.D=nn.Parameter(torch.ones(s.di))
        s.op=nn.Linear(s.di,dm,bias=False); s.nm=nn.LayerNorm(dm)
    def forward(s,x):
        B,L,_=x.shape; res=x; xc,z=s.inp(x).chunk(2,-1)
        xc=F.silu(s.cv(xc.transpose(1,2))[:,:,:L].transpose(1,2))
        p=s.xp(xc); Bp=p[:,:,:s.ds]; Cp=p[:,:,s.ds:2*s.ds]
        dt=F.softplus(s.dtp(p[:,:,-1:])); A=-torch.exp(s.Al)
        h=torch.zeros(B,s.di,s.ds,device=x.device); outs=[]
        for t in range(L):                              # TRUE recurrence
            dA=torch.exp(A.unsqueeze(0)*dt[:,t,:].unsqueeze(-1))
            dB=dt[:,t,:].unsqueeze(-1)*Bp[:,t,:].unsqueeze(1)
            h=dA*h+dB*xc[:,t,:].unsqueeze(-1)
            outs.append((h*Cp[:,t,:].unsqueeze(1)).sum(-1)+s.D*xc[:,t,:])
        return s.nm(s.op(torch.stack(outs,1)*F.silu(z))+res)
class MambaBlock(nn.Module):
    def __init__(s,dm,ds=16):
        super().__init__(); s.ssm=SelectiveSSM(dm,ds)
        s.ffn=nn.Sequential(nn.Linear(dm,dm*2),nn.GELU(),nn.Dropout(0.1),nn.Linear(dm*2,dm)); s.nm=nn.LayerNorm(dm)
    def forward(s,x): x=s.ssm(x); return s.nm(x+s.ffn(x))
class MambaKAN(nn.Module):
    def __init__(s,V,nc,L,dm=64,nl=2,ds=16):
        super().__init__(); s.emb=nn.Embedding(V,EMB,padding_idx=0)
        s.kan=KANLayer(EMB,dm); s.pos=nn.Parameter(torch.randn(1,L,dm)*0.02)
        s.mb=nn.ModuleList([MambaBlock(dm,ds) for _ in range(nl)])
        s.cl=nn.Sequential(nn.Linear(dm*2,128),nn.GELU(),nn.Dropout(0.3),nn.Linear(128,nc))
    def forward(s,x):
        B,L=x.shape; e=s.kan(s.emb(x).reshape(B*L,EMB)).reshape(B,L,-1)+s.pos[:,:L,:]
        for m in s.mb: e=m(e)
        return s.cl(torch.cat([e.mean(1),e.max(1).values],-1))
class LSTMcls(nn.Module):
    def __init__(s,V,nc):
        super().__init__(); s.emb=nn.Embedding(V,EMB,padding_idx=0)
        s.l=nn.LSTM(EMB,64,2,batch_first=True,dropout=0.1,bidirectional=True)
        s.c=nn.Sequential(nn.Linear(128,64),nn.ReLU(),nn.Dropout(0.3),nn.Linear(64,nc))
    def forward(s,x): o,_=s.l(s.emb(x)); return s.c(o[:,-1,:])
class TransformerCls(nn.Module):
    def __init__(s,V,nc,L):
        super().__init__(); s.emb=nn.Embedding(V,EMB,padding_idx=0)
        s.pos=nn.Parameter(torch.randn(1,L,EMB)*0.02)
        s.t=nn.TransformerEncoder(nn.TransformerEncoderLayer(EMB,4,128,0.1,batch_first=True),2)
        s.c=nn.Sequential(nn.Linear(EMB,64),nn.ReLU(),nn.Dropout(0.3),nn.Linear(64,nc))
    def forward(s,x): return s.c(s.t(s.emb(x)+s.pos[:,:x.shape[1],:]).mean(1))
class FocalLoss(nn.Module):
    def __init__(s,a=None,g=2.0): super().__init__(); s.a=a; s.g=g
    def forward(s,o,t):
        ce=F.cross_entropy(o,t,weight=s.a,reduction="none"); pt=torch.exp(-ce)
        return (((1-pt)**s.g)*ce).mean()

