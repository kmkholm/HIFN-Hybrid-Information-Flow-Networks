def make_model(name, L):
    return (MambaKAN(F_DIM, L=L) if name=="MambaKAN-APT" else TORCH_MODELS[name](F_DIM)).to(DEVICE)

def train_eval_torch(name, Xtr, ytr, Xte, yte, L, seed):
    torch.manual_seed(seed); np.random.seed(seed)
    m = make_model(name, L)
    cw = torch.tensor([len(ytr)/(5*max(1,(ytr==c).sum())) for c in range(5)],
                      dtype=torch.float32, device=DEVICE)
    crit = FocalLoss(cw, 2.0)
    opt = torch.optim.AdamW(m.parameters(), lr=1e-3, weight_decay=1e-4)
    sch = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=EPOCHS, eta_min=1e-6)
    Xtr_t = torch.tensor(Xtr); ytr_t = torch.tensor(ytr)
    n=len(Xtr_t)
    for ep in range(EPOCHS):
        m.train(); perm=torch.randperm(n)
        for i in range(0,n,BATCH):
            b=perm[i:i+BATCH]; xb=Xtr_t[b].to(DEVICE); yb=ytr_t[b].to(DEVICE)
            opt.zero_grad(); loss=crit(m(xb), yb); loss.backward()
            nn.utils.clip_grad_norm_(m.parameters(),1.0); opt.step()
        sch.step()
    m.eval(); preds=[]
    with torch.no_grad():
        Xte_t=torch.tensor(Xte)
        for i in range(0,len(Xte_t),BATCH):
            preds.append(m(Xte_t[i:i+BATCH].to(DEVICE)).argmax(1).cpu().numpy())
    return np.concatenate(preds), m

