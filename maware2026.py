def causal_windows(X, y, day, L):
    """Every flow becomes a target; context = up to L preceding flows in same day."""
    N = len(X); Xs = np.zeros((N, L, X.shape[1]), np.float32)
    for d in sorted(set(day.tolist())):
        idx = np.where(day == d)[0]; Xd = X[idx]
        for j, gi in enumerate(idx):
            s = max(0, j-L+1); win = Xd[s:j+1]
            if len(win) < L:
                win = np.concatenate([np.repeat(Xd[s:s+1], L-len(win), 0), win], 0)
            Xs[gi] = win
    return Xs, y.copy()

